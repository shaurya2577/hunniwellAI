-- 001: foundation for the weekly file ingest (docs/ingestion-plan.md).
--
-- Adds time periods, ingest runs, a per-file document registry and company
-- aliases; tags sources/claims with document, period and run. Every statement
-- is idempotent so the migration can be re-applied safely (apply_schema runs
-- schema.sql and then every migration on each call).
--
-- claims_idem is deliberately NOT changed: each document maps to exactly one
-- source (unique sources.document_id) and a document belongs to one period, so
-- (company, field, value, source) already separates periods.

create table if not exists schema_migrations (
  version text primary key,
  applied_at timestamptz default now()
);

create table if not exists periods (
  id uuid primary key default gen_random_uuid(),
  label text unique not null,
  kind text not null check (kind in ('event', 'weekly', 'historical')),
  starts_on date,
  ends_on date,
  created_at timestamptz default now()
);

create table if not exists ingest_runs (
  id uuid primary key default gen_random_uuid(),
  started_at timestamptz default now(),
  finished_at timestamptz,
  status text not null default 'running'
    check (status in ('running', 'succeeded', 'partial', 'failed', 'dry_run')),
  root text,
  host text,
  stats jsonb not null default '{}'::jsonb
);

create table if not exists documents (
  id uuid primary key default gen_random_uuid(),
  company_id uuid references companies(id) on delete cascade,
  relpath text unique not null,
  sha256 text,
  size_bytes bigint,
  mtime timestamptz,
  file_kind text,
  period_id uuid references periods(id),
  status text not null default 'active'
    check (status in ('active', 'deleted', 'skipped_large', 'unsupported', 'empty', 'error')),
  error text,
  first_seen_run uuid references ingest_runs(id),
  last_seen_run uuid references ingest_runs(id),
  last_ingested_run uuid references ingest_runs(id),
  extractor_version text,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create index if not exists documents_company on documents(company_id);

create table if not exists company_aliases (
  alias_norm text primary key,
  company_id uuid not null references companies(id) on delete cascade,
  created_at timestamptz default now()
);

-- Human-friendly company number (HW-0001 style ids in the UI/MCP layer).
alter table companies
  add column if not exists company_code bigint generated by default as identity;
create unique index if not exists companies_company_code on companies(company_code);

alter table sources add column if not exists document_id uuid references documents(id) on delete cascade;
alter table sources add column if not exists period_id uuid references periods(id);
create unique index if not exists sources_document on sources(document_id) where document_id is not null;

alter table claims add column if not exists period_id uuid references periods(id);
alter table claims add column if not exists run_id uuid references ingest_runs(id);
alter table claims add column if not exists as_of date;
create index if not exists claims_period on claims(period_id);
create index if not exists claims_source_status on claims(source_id, status);

-- Supabase exposes the public schema over its REST API; with RLS on and no
-- policies, the anon/authenticated keys can read nothing. The table owner
-- (the role the ingest and MCP connect as) is unaffected.
alter table companies enable row level security;
alter table company_appearances enable row level security;
alter table sources enable row level security;
alter table claims enable row level security;
alter table periods enable row level security;
alter table ingest_runs enable row level security;
alter table documents enable row level security;
alter table company_aliases enable row level security;
alter table schema_migrations enable row level security;
